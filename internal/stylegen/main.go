// Command stylegen writes ui/style_merge_gen.go: the mergeFrom and layered
// methods of each widget style type (a struct named ...Style whose fields are
// Styles, other widget style types, or float32 sizes).
//
// mergeFrom merges in place, through pointers, with Style.mergeFrom for each
// part. A widget style is several KB, and TinyGo turns every copy of one into
// code for each of its fields, so value methods that return a merged copy made
// the web build several hundred KB larger. layered is written out for each type,
// not shared as a generic function: Go's escape analysis cannot see through the
// method calls of a generic one, and would move every widget's styles to the heap.
//
// A type whose merge needs more than that (TabsStyle) has a mergeFrom written
// by hand, and stylegen writes only its layered.
//
// Run it with go generate in package ui.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"log"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

// header starts the file that stylegen writes.
const header = "// Code generated by internal/stylegen; DO NOT EDIT."

func main() {
	dir := flag.String("dir", ".", "the directory of package ui")
	out := flag.String("out", "style_merge_gen.go", "the file to write, in -dir unless absolute")
	flag.Parse()

	fset := token.NewFileSet()
	files, err := filepath.Glob(filepath.Join(*dir, "*.go"))
	if err != nil {
		log.Fatal(err)
	}
	structs := map[string]*ast.StructType{}
	handwritten := map[string]bool{} // types with a mergeFrom of their own
	for _, f := range files {
		if strings.HasSuffix(f, "_test.go") {
			continue
		}
		src, err := os.ReadFile(f)
		if err != nil {
			log.Fatal(err)
		}
		if bytes.HasPrefix(src, []byte(header)) {
			continue // stylegen's own output
		}
		af, err := parser.ParseFile(fset, f, src, parser.SkipObjectResolution)
		if err != nil {
			log.Fatal(err)
		}
		for _, d := range af.Decls {
			if fd, ok := d.(*ast.FuncDecl); ok && fd.Name.Name == "mergeFrom" && fd.Recv != nil {
				if star, ok := fd.Recv.List[0].Type.(*ast.StarExpr); ok {
					if id, ok := star.X.(*ast.Ident); ok {
						handwritten[id.Name] = true
					}
				}
			}
			gd, ok := d.(*ast.GenDecl)
			if !ok || gd.Tok != token.TYPE {
				continue
			}
			for _, s := range gd.Specs {
				ts := s.(*ast.TypeSpec)
				if st, ok := ts.Type.(*ast.StructType); ok && ts.TypeParams == nil {
					structs[ts.Name.Name] = st
				}
			}
		}
	}

	// A widget style type is a ...Style struct (not Style itself) whose fields
	// are all Styles, widget style types or float32s. Repeat until no type
	// drops out, since a field may name a type that turns out not to be one.
	widget := map[string]bool{}
	for name := range structs {
		if name != "Style" && strings.HasSuffix(name, "Style") {
			widget[name] = true
		}
	}
	for changed := true; changed; {
		changed = false
		for name := range widget {
			for _, f := range structs[name].Fields.List {
				id, ok := f.Type.(*ast.Ident)
				if !ok || (id.Name != "Style" && id.Name != "float32" && !widget[id.Name]) {
					delete(widget, name)
					changed = true
					break
				}
			}
		}
	}

	names := make([]string, 0, len(widget))
	for name := range widget {
		names = append(names, name)
	}
	sort.Strings(names)

	var b bytes.Buffer
	b.WriteString(header + "\n\npackage ui\n")
	for _, name := range names {
		fmt.Fprintf(&b, "\n// layered merges layers over s, the built-in look, in order (see layeredRecorded).\n")
		fmt.Fprintf(&b, "func (s *%s) layered(ctx *Context, layers ...layer[%s]) {\n", name, name)
		b.WriteString("\thc := ctx.Theme().HighContrast\n")
		b.WriteString("\tif ctx.rt.insp != nil {\n")
		b.WriteString("\t\t// The inspector's merge works on heap copies, so that s and the layers stay on the stack.\n")
		fmt.Fprintf(&b, "\t\tbase := new(%s)\n\t\tcopyLarge(base, s)\n", name)
		fmt.Fprintf(&b, "\t\tcopies := make([]layer[%s], len(layers))\n", name)
		b.WriteString("\t\tfor i, l := range layers {\n")
		fmt.Fprintf(&b, "\t\t\tcopies[i] = layer[%s]{new(%s), l.instance}\n", name, name)
		b.WriteString("\t\t\tcopyLarge(copies[i].s, l.s)\n\t\t}\n")
		b.WriteString("\t\tlayeredRecorded(base, copies, hc)\n\t\tcopyLarge(s, base)\n")
		b.WriteString("\t\treturn\n\t}\n")
		b.WriteString("\tfor i := range layers {\n\t\ts.mergeFrom(layers[i].s, hc)\n\t}\n}\n")
		if handwritten[name] {
			continue
		}
		fmt.Fprintf(&b, "\n// mergeFrom applies o on top of s in place, part by part (see Style.mergeFrom).\n")
		fmt.Fprintf(&b, "func (s *%s) mergeFrom(o *%s, plain bool) {\n", name, name)
		for _, f := range structs[name].Fields.List {
			typ := f.Type.(*ast.Ident).Name
			fieldNames := f.Names
			if len(fieldNames) == 0 { // an embedded field
				fieldNames = []*ast.Ident{ast.NewIdent(typ)}
			}
			for _, n := range fieldNames {
				if typ == "float32" {
					fmt.Fprintf(&b, "\tif o.%s != 0 {\n\t\ts.%s = o.%s\n\t}\n", n.Name, n.Name, n.Name)
					continue
				}
				fmt.Fprintf(&b, "\ts.%s.mergeFrom(&o.%s, plain)\n", n.Name, n.Name)
			}
		}
		b.WriteString("}\n")
	}
	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	path := *out
	if !filepath.IsAbs(path) {
		path = filepath.Join(*dir, path)
	}
	if err := os.WriteFile(path, src, 0o644); err != nil {
		log.Fatal(err)
	}
}

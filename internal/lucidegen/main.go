// Command lucidegen writes the Lucide icons of the icons package from the SVG
// files of a pinned Lucide release. The go:generate line in icons/generate.go
// runs it:
//
//	go run ../internal/lucidegen -out lucide_gen.go
//
// It downloads the release's source archive from GitHub, or reads it from -zip,
// and checks the SVG files in it against a SHA-256 recorded here, so the icons
// are those of the release whatever archive bytes GitHub serves.
//
// Each file becomes a const with the inside of its SVG, and a var that names the
// icon: arrow-down.svg is icons.ArrowDown. The var holds only the name and the
// const, so an icon costs a binary only when the binary names it.
package main

import (
	"archive/zip"
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"flag"
	"fmt"
	"go/format"
	"go/token"
	"io"
	"log"
	"net/http"
	"os"
	"path"
	"regexp"
	"sort"
	"strings"
	"unicode"
)

// The pinned Lucide release: its tag, its commit, and the SHA-256 of its SVG files
// (see iconsHash). To update Lucide, change the three, run go generate ./icons, and
// update third_party/lucide/README.md.
const (
	lucideTag    = "1.61.0"
	lucideCommit = "c29c276f16590cf017126671535ad8c792be64d8"
	lucideIcons  = "36b1548a61d8f4404c059757999af57899ba9e56ec325e1fe91fd8869d0344fc"
)

var lucideRelease = lucideTag + " (tag " + lucideTag + ", commit " + lucideCommit + ")"

// reserved names are declared by hand in the icons package. A Lucide icon with
// one of these names is declared as Lucide plus its name: maximize.svg becomes
// icons.LucideMaximize, and icons.Maximize keeps its own drawing.
var reserved = map[string]bool{
	"All": true, "Icon": true, "Alert": true, "Dashboard": true, "Filter": true,
	"Home": true, "MoreHorizontal": true, "Refresh": true, "Maximize": true,
	"Minimize": true, "Restore": true, "StarFilled": true,
}

var (
	rootRe    = regexp.MustCompile(`(?s)<svg\b[^>]*>`)
	spaceRe   = regexp.MustCompile(`\s+`)
	betweenRe = regexp.MustCompile(`>\s+<`)
	closeRe   = regexp.MustCompile(`\s*/>`)
)

// rootAttrs are the attributes of the root element that every icon shares. The
// wrapper in icons/icon.go supplies them, so an icon with other ones is an error.
var rootAttrs = []string{
	`viewBox="0 0 24 24"`, `fill="none"`, `stroke="currentColor"`, `stroke-width="2"`,
	`stroke-linecap="round"`, `stroke-linejoin="round"`,
}

func main() {
	zipPath := flag.String("zip", "", "the release's source archive; empty downloads it from GitHub")
	out := flag.String("out", "", "Go file to write")
	flag.Parse()
	if *out == "" {
		log.Fatal("lucidegen: -out is required")
	}
	icons, err := readRelease(*zipPath)
	if err != nil {
		log.Fatal("lucidegen: ", err)
	}
	if got := iconsHash(icons); got != lucideIcons {
		log.Fatalf("lucidegen: the SVG files of Lucide %s hash to %s, want %s", lucideTag, got, lucideIcons)
	}
	files := make([]string, 0, len(icons))
	for name := range icons {
		files = append(files, name)
	}
	sort.Strings(files)

	var consts, vars, list bytes.Buffer
	seen := map[string]bool{}
	for _, file := range files {
		body, err := inside(icons[file])
		if err != nil {
			log.Fatalf("lucidegen: %s: %v", file, err)
		}
		name := camel(file)
		if reserved[name] {
			name = "Lucide" + name
		}
		if !token.IsIdentifier(name) || seen[name] {
			log.Fatalf("lucidegen: %s: bad or repeated Go name %q", file, name)
		}
		seen[name] = true
		constName := lower(name) + "Src"
		fmt.Fprintf(&consts, "\t%s = `%s`\n", constName, body)
		fmt.Fprintf(&vars, "\t// %s is the Lucide %q icon.\n\t%s = &Icon{Name: %q, src: %s}\n\n", name, file, name, file, constName)
		fmt.Fprintf(&list, "\t\t%s,\n", name)
	}

	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by internal/lucidegen from Lucide %s. DO NOT EDIT.\n\n", lucideRelease)
	b.WriteString("package icons\n\n")
	b.WriteString("// The SVG source of each icon, without its root element (see svgStart in icon.go).\n")
	fmt.Fprintf(&b, "const (\n%s)\n\n", consts.String())
	b.WriteString("// The Lucide icons, by their CamelCase names.\n")
	fmt.Fprintf(&b, "var (\n%s)\n\n", strings.TrimSuffix(vars.String(), "\n\n")+"\n")
	b.WriteString("// lucideIcons lists every Lucide icon. It is a function so that an app which\n")
	b.WriteString("// never calls it does not link the icons it does not name.\n")
	fmt.Fprintf(&b, "func lucideIcons() []*Icon {\n\treturn []*Icon{\n%s\t}\n}\n", list.String())

	formatted, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatalf("lucidegen: %v", err)
	}
	if err := os.WriteFile(*out, formatted, 0o644); err != nil {
		log.Fatal(err)
	}
	fmt.Printf("lucidegen: wrote %d icons to %s\n", len(files), *out)
}

// inside returns the elements inside an icon's SVG, joined without the spaces
// between them. It is an error when the root element differs from the wrapper's.
func inside(data []byte) (string, error) {
	loc := rootRe.FindIndex(data)
	end := bytes.LastIndex(data, []byte("</svg>"))
	if loc == nil || end < loc[1] {
		return "", fmt.Errorf("no svg element")
	}
	root := string(data[loc[0]:loc[1]])
	for _, want := range rootAttrs {
		if !strings.Contains(root, want) {
			return "", fmt.Errorf("the root element lacks %s", want)
		}
	}
	s := strings.TrimSpace(string(data[loc[1]:end]))
	s = spaceRe.ReplaceAllString(s, " ")
	s = betweenRe.ReplaceAllString(s, "><")
	s = closeRe.ReplaceAllString(s, "/>")
	if strings.Contains(s, "`") {
		return "", fmt.Errorf("the source has a backtick")
	}
	return s, nil
}

// camel turns a file name into a Go name: arrow-down becomes ArrowDown, and
// a-arrow-down becomes AArrowDown.
func camel(file string) string {
	var b strings.Builder
	for _, part := range strings.Split(file, "-") {
		if part == "" {
			continue
		}
		r := []rune(part)
		r[0] = unicode.ToUpper(r[0])
		b.WriteString(string(r))
	}
	return b.String()
}

// lower lowers the first letter of a Go name, for the name of its const.
func lower(name string) string {
	r := []rune(name)
	r[0] = unicode.ToLower(r[0])
	return string(r)
}

// readRelease returns the SVG files of the release's icons directory, by name
// without ".svg", from the archive at zipPath, or downloaded when zipPath is "".
func readRelease(zipPath string) (map[string][]byte, error) {
	var data []byte
	var err error
	if zipPath != "" {
		data, err = os.ReadFile(zipPath)
	} else {
		data, err = download("https://github.com/lucide-icons/lucide/archive/refs/tags/" + lucideTag + ".zip")
	}
	if err != nil {
		return nil, err
	}
	zr, err := zip.NewReader(bytes.NewReader(data), int64(len(data)))
	if err != nil {
		return nil, err
	}
	icons := map[string][]byte{}
	for _, f := range zr.File {
		// The archive holds lucide-<tag>/icons/<name>.svg among the rest of the repository.
		dir, base := path.Split(f.Name)
		if !strings.HasSuffix(dir, "/icons/") || strings.Count(dir, "/") != 2 || !strings.HasSuffix(base, ".svg") {
			continue
		}
		rc, err := f.Open()
		if err != nil {
			return nil, err
		}
		b, err := io.ReadAll(rc)
		rc.Close()
		if err != nil {
			return nil, err
		}
		icons[strings.TrimSuffix(base, ".svg")] = b
	}
	if len(icons) == 0 {
		return nil, fmt.Errorf("no icons/*.svg in the archive of Lucide %s", lucideTag)
	}
	return icons, nil
}

func download(url string) ([]byte, error) {
	resp, err := http.Get(url)
	if err != nil {
		return nil, err
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("GET %s: %s", url, resp.Status)
	}
	return io.ReadAll(resp.Body)
}

// iconsHash is the SHA-256, in hex, of the icons in name order, each as its name,
// a zero byte, its file and a zero byte.
func iconsHash(icons map[string][]byte) string {
	names := make([]string, 0, len(icons))
	for n := range icons {
		names = append(names, n)
	}
	sort.Strings(names)
	h := sha256.New()
	for _, n := range names {
		h.Write([]byte(n))
		h.Write([]byte{0})
		h.Write(icons[n])
		h.Write([]byte{0})
	}
	return hex.EncodeToString(h.Sum(nil))
}
